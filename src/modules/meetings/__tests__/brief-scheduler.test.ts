import { describe, expect, it } from "vitest";
import { scopedDb } from "@/lib/db/scoped";
import { createTestAdmin } from "@/test/fixtures";
import { dispatchOutbox, OUTBOX_ROUTES } from "@/lib/jobs/outbox";
import { PROCESSORS } from "@/worker/processors";
import type { AiProvider } from "@/lib/ai";
import {
  prepareBrief,
  scheduleBriefForMeeting,
  sweepUpcomingMeetingBriefs,
} from "../service";
import type { Job } from "bullmq";

const makeMockProvider = (accountId: string): AiProvider => ({
  name: "recorded",
  async generateStructured<T>() {
    return {
      output: {
        reasoningSummary: "Prepared brief from meeting details and account health.",
        confidence: 0.9,
        citations: [{ sourceType: "Account", sourceId: accountId }],
        proposedActions: [],
        title: "Auto Brief for Acme",
        summary: "Upcoming meeting brief generated by worker.",
        decisions: [],
        actionItems: [],
        suggestedQuestions: ["Any renewal blockers?"],
        healthHighlights: ["Overall health is good"],
        metrics: { overallHealth: 88, band: "GOOD" },
      } as T,
      stopReason: "end_turn",
      model: "recorded",
      requestId: null,
      inputTokens: 10,
      outputTokens: 20,
      latencyMs: 5,
    };
  },
});

describe("Pre-call brief scheduler and worker job (T-30)", () => {
  it("schedules brief outbox event at T-30, dispatches to agents queue, and processor prepares brief", async () => {
    const admin = await createTestAdmin("brief-sched-1");
    const ws = admin.workspace.id;
    const db = scopedDb({ workspaceId: ws });

    const account = await db.account.create({
      data: {
        workspaceId: ws,
        name: "Acme Brief Scheduling",
        tier: "HIGH_TOUCH",
        ownerMembershipId: admin.membership.id,
      },
    });

    // Create a meeting starting 1 hour from now
    const now = Date.now();
    const startsAt = new Date(now + 60 * 60 * 1000); // T+60m
    const endsAt = new Date(now + 90 * 60 * 1000);

    const meeting = await db.meeting.create({
      data: {
        workspaceId: ws,
        accountId: account.id,
        title: "Upcoming QBR Prep",
        startsAt,
        endsAt,
        status: "SCHEDULED",
      },
    });

    // 1. scheduleBriefForMeeting schedules outbox event at T-30
    await db.$tenantTransaction(async (tx) => {
      await scheduleBriefForMeeting(tx, ws, meeting);
    });

    const expectedAvailableAt = new Date(startsAt.getTime() - 30 * 60 * 1000);
    const events = await db.outboxEvent.findMany({
      where: { workspaceId: ws, type: "meetings.prepareBrief" },
    });
    expect(events.length).toBeGreaterThanOrEqual(1);
    const event = events.find((e) => (e.payload as Record<string, unknown>).meetingId === meeting.id);
    expect(event).toBeDefined();
    expect(Math.abs(event!.availableAt.getTime() - expectedAvailableAt.getTime())).toBeLessThan(1000);

    // 2. Mock enqueue and dispatch outbox
    const enqueued: Array<{ queue: string; job: string; data: unknown }> = [];
    // Mark available now so dispatchOutbox picks it up
    await db.outboxEvent.update({
      where: { id: event!.id },
      data: { availableAt: new Date(now - 1000) },
    });

    await dispatchOutbox(OUTBOX_ROUTES, {
      workspaceId: ws,
      enqueue: async (queue, job, data) => {
        enqueued.push({ queue, job, data });
      },
    });

    expect(enqueued.length).toBe(1);
    expect(enqueued[0]!.queue).toBe("agents");
    expect(enqueued[0]!.job).toBe("meetings.prepareBrief");
    expect((enqueued[0]!.data as Record<string, unknown>).meetingId).toBe(meeting.id);

    // 3. Worker processor executes the job
    const processor = PROCESSORS.agents?.["meetings.prepareBrief"];
    expect(processor).toBeDefined();

    const mockJob = {
      name: "meetings.prepareBrief",
      data: enqueued[0]!.data,
    } as Job;

    // Run processor with mockProvider deps
    await prepareBrief(
      { workspaceId: ws },
      { meetingId: meeting.id },
      { provider: makeMockProvider(account.id) },
    );

    const updated = await db.meeting.findUniqueOrThrow({
      where: { id: meeting.id },
      include: { briefDocument: true },
    });
    expect(updated.briefDocument).not.toBeNull();
    expect(updated.briefDocument!.title).toBe("Auto Brief for Acme");
    expect(updated.briefDocument!.kind).toBe("PRE_CALL_BRIEF");
  });

  it("sweepUpcomingMeetingBriefs generates briefs for meetings within the 45m window", async () => {
    const admin = await createTestAdmin("brief-sched-2");
    const ws = admin.workspace.id;
    const db = scopedDb({ workspaceId: ws });

    const account = await db.account.create({
      data: {
        workspaceId: ws,
        name: "Acme Sweep Test",
        tier: "HIGH_TOUCH",
        ownerMembershipId: admin.membership.id,
      },
    });

    const now = new Date();
    const startsAt = new Date(now.getTime() + 20 * 60 * 1000); // 20 min from now
    const endsAt = new Date(now.getTime() + 50 * 60 * 1000);

    const meeting = await db.meeting.create({
      data: {
        workspaceId: ws,
        accountId: account.id,
        title: "Sweep Imminent Meeting",
        startsAt,
        endsAt,
        status: "SCHEDULED",
      },
    });

    const count = await sweepUpcomingMeetingBriefs({ workspaceId: ws }, now, {
      provider: makeMockProvider(account.id),
    });
    expect(count).toBeGreaterThanOrEqual(1);

    const afterSweep = await db.meeting.findUniqueOrThrow({
      where: { id: meeting.id },
      include: { briefDocument: true },
    });
    expect(afterSweep.briefDocument).not.toBeNull();
    expect(afterSweep.briefDocument!.title).toBe("Auto Brief for Acme");
  });
});
